"""Measure the code paths that line and branch coverage can't see.

Coverage.py's branches are jumps between lines, so it can't tell whether each part of a condition
ran both ways, and it doesn't see Jinja templates at all. This instruments a scratch copy, runs the
suite, and reports three things:

- Condition coverage: every `if`, `while`, `x if c else y`, comprehension filter, and and/or operand
  must evaluate both true and false.
- Operands reached: the right side of every and/or must be evaluated at least once.
- Template branches: every {% if %} branch and both sides of {{ x if c else y }} must render.

The folder being measured is only read.

Usage, from the repo root: python tools/path_coverage.py [--root folder] [-m "not browser"]
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

RUNTIME = '''"""Records which instrumented paths ran. Generated by path_coverage.py."""
import atexit, json, os

hits = set()


def hit(arm, value=None):
    hits.add(arm)
    return value


def cond(arm, value):
    hits.add(f"{arm}:{bool(value)}")
    return value


@atexit.register
def _dump():
    with open(os.path.join(os.environ["HITS_DIR"], f"hits-{os.getpid()}.json"), "w") as out:
        json.dump(sorted(hits), out)


def instrument_templates(env):
    from jinja2 import nodes

    arms = {}
    original_parse = env._parse

    def add_arm(name, lineno, kind):
        arm = f"T{len(arms)}"
        arms[arm] = {"file": f"app/templates/{name}", "line": lineno, "kind": kind}
        return arm

    def marker(arm, lineno):
        statement = nodes.ExprStmt(nodes.Call(nodes.Name("_tpl_hit", "load"), [nodes.Const(arm)], [], None, None))
        statement.set_lineno(lineno)
        statement.set_environment(env)
        return statement

    def wrapped(arm, expr, lineno):
        call = nodes.Call(nodes.Name("_tpl_hit", "load"), [nodes.Const(arm), expr], [], None, None)
        call.set_lineno(lineno)
        call.set_environment(env)
        return call

    def parse(source, name=None, filename=None):
        tree = original_parse(source, name, filename)
        ifs = list(tree.find_all(nodes.If))
        elifs = {id(branch) for node in ifs for branch in node.elif_}
        for node in ifs:
            line = node.lineno
            node.body.insert(0, marker(add_arm(name, line, "elif" if id(node) in elifs else "if: true"), line))
            if id(node) in elifs:
                continue
            kind = "else" if node.else_ else "if: false"
            node.else_.insert(0, marker(add_arm(name, line, kind), line))
        for node in list(tree.find_all(nodes.CondExpr)):
            line = node.lineno
            node.expr1 = wrapped(add_arm(name, line, "x if c else y: then"), node.expr1, line)
            if node.expr2 is not None:
                node.expr2 = wrapped(add_arm(name, line, "x if c else y: else"), node.expr2, line)
        return tree

    env._parse = parse
    env.globals["_tpl_hit"] = hit
    for name in env.list_templates():
        env.get_template(name)
    with open(os.path.join(os.environ["HITS_DIR"], "template-arms.json"), "w") as out:
        json.dump(arms, out)
'''


class Instrument(ast.NodeTransformer):
    def __init__(self, file: str, lines: list[str], conditions: dict, operands: dict):
        self.file, self.lines, self.conditions, self.operands = file, lines, conditions, operands

    def _code(self, lineno: int) -> str:
        return self.lines[lineno - 1].strip()

    def _condition(self, node: ast.expr, kind: str) -> ast.expr:
        """Record both outcomes of one condition. and/or and not are broken into their parts."""
        if isinstance(node, ast.BoolOp):
            node.values = [self._condition(value, f"{kind}: and/or operand") for value in node.values]
            return node
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not):
            node.operand = self._condition(node.operand, kind)
            return node
        arm = f"C{len(self.conditions)}"
        self.conditions[arm] = {"file": self.file, "line": node.lineno, "kind": kind, "code": self._code(node.lineno)}
        return ast.copy_location(ast.Call(ast.Name("_cov_cond", ast.Load()), [ast.Constant(arm), node], []), node)

    def visit_If(self, node: ast.If) -> ast.stmt:
        self.generic_visit(node)
        node.test = self._condition(node.test, "if")
        return node

    def visit_While(self, node: ast.While) -> ast.stmt:
        self.generic_visit(node)
        node.test = self._condition(node.test, "while")
        return node

    def visit_IfExp(self, node: ast.IfExp) -> ast.expr:
        self.generic_visit(node)
        node.test = self._condition(node.test, "x if c else y")
        return node

    def visit_comprehension(self, node: ast.comprehension) -> ast.comprehension:
        self.generic_visit(node)
        node.ifs = [self._condition(test, "comprehension filter") for test in node.ifs]
        return node

    def visit_BoolOp(self, node: ast.BoolOp) -> ast.expr:
        """and/or used as a value, such as `name or "paper"`: its right side must run, and its left must go both ways."""
        self.generic_visit(node)
        for i in range(1, len(node.values)):
            arm = f"O{len(self.operands)}"
            value = node.values[i]
            self.operands[arm] = {"file": self.file, "line": value.lineno, "kind": "right side of and/or reached", "code": self._code(value.lineno)}
            node.values[i] = ast.copy_location(ast.Call(ast.Name("_cov_hit", ast.Load()), [ast.Constant(arm), value], []), value)
        return node


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("-m", dest="marker", default=None, help='a pytest marker expression, for example "not browser"')
    args = parser.parse_args()
    root = args.root.resolve()

    work = Path(tempfile.mkdtemp(prefix="path-coverage-"))
    for name in ("app", "tests"):
        shutil.copytree(root / name, work / name, ignore=shutil.ignore_patterns("__pycache__", ".hypothesis"))
    if (root / "docs").is_dir():  # tests/test_contracts.py compares the code with these
        shutil.copytree(root / "docs", work / "docs")
    for name in ("pytest.ini", ".env.example", ".gitignore", "README.md", "CLAUDE.md", "requirements.txt", "requirements-dev.txt"):
        if (root / name).exists():
            shutil.copy(root / name, work / name)
    hits_dir = work / "_hits"
    hits_dir.mkdir()

    conditions: dict = {}
    operands: dict = {}
    for path in sorted((work / "app").glob("*.py")):
        text = path.read_text()
        tree = Instrument(f"app/{path.name}", text.splitlines(), conditions, operands).visit(ast.parse(text))
        if path.name != "__init__.py":
            position = 0
            for i, statement in enumerate(tree.body):
                is_docstring = i == 0 and isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Constant)
                is_future = isinstance(statement, ast.ImportFrom) and statement.module == "__future__"
                if is_docstring or is_future:
                    position = i + 1
            tree.body.insert(position, ast.parse("from app._path_hits import cond as _cov_cond, hit as _cov_hit").body[0])
        path.write_text(ast.unparse(tree) + "\n")
    (work / "app" / "_path_hits.py").write_text(RUNTIME)
    main_py = work / "app" / "main.py"
    main_py.write_text(main_py.read_text() + "\nfrom app._path_hits import instrument_templates\ninstrument_templates(templates.env)\n")

    env = os.environ | {"HITS_DIR": str(hits_dir), "PYTHONDONTWRITEBYTECODE": "1", "HYPOTHESIS_PROFILE": "mutation"}
    # test_contracts.py reads the source, which this tool has rewritten. The .env tests start config.py alone
    # in a new process, away from this tool's helper. Neither exercises any app paths in this process.
    command = [sys.executable, "-m", "pytest", "-q", "--tb=no", "-p", "no:cacheprovider", "-W", "ignore", "--ignore=tests/test_contracts.py", "-k", "not dotenv_file"]
    if args.marker:
        command += ["-m", args.marker]
    finished = subprocess.run(command, cwd=work, env=env, capture_output=True, text=True, timeout=1200)
    for line in finished.stdout.splitlines():
        if line.startswith(("FAILED", "ERROR")):
            print(line[:150])
    print(next((line for line in reversed(finished.stdout.splitlines()) if re.search(r"\d+ (passed|failed)", line)), finished.stdout[-500:] + finished.stderr[-500:]))

    hits: set[str] = set()
    for hit_file in hits_dir.glob("hits-*.json"):
        hits.update(json.loads(hit_file.read_text()))
    template_arms = json.loads((hits_dir / "template-arms.json").read_text())
    for arm in template_arms.values():
        arm["code"] = (root / arm["file"]).read_text().splitlines()[arm["line"] - 1].strip()

    outcomes = 2 * len(conditions)
    seen = sum(f"{arm}:{value}" in hits for arm in conditions for value in (True, False))
    print(f"\nCondition coverage: {seen} of {outcomes} outcomes ({100 * seen / outcomes:.1f}%)")
    for arm, info in sorted(conditions.items(), key=lambda item: (item[1]["file"], item[1]["line"])):
        missing = [str(value) for value in (True, False) if f"{arm}:{value}" not in hits]
        if missing:
            print(f"  NEVER {'/'.join(missing):11} {info['file']}:{info['line']}  [{info['kind']}]  {info['code'][:95]}")

    for title, arms in (("Operands reached", operands), ("Template branches", template_arms)):
        missed = [info for arm, info in arms.items() if arm not in hits]
        print(f"\n{title}: {len(arms) - len(missed)} of {len(arms)} ({100 * (len(arms) - len(missed)) / len(arms):.1f}%)")
        for info in sorted(missed, key=lambda item: (item["file"], item["line"])):
            print(f"  NEVER RAN {info['file']}:{info['line']}  [{info['kind']}]  {info['code'][:95]}")
    shutil.rmtree(work, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
